// Copies a fixed set of Lucide icon SVGs from the lucide-static devDependency
// into renderer/icons.js as inline markup, so the app never fetches or
// bundles icons at runtime - everything ships baked into the app already.
'use strict';
const fs = require('fs');
const path = require('path');

const ICONS = [
  'settings', 'sun', 'moon', 'image', 'pin', 'pin-off', 'tag', 'hash',
  'link', 'search', 'plus', 'trash-2', 'x', 'minimize-2', 'maximize-2', 'pencil', 'eye',
  'command', 'palette', 'folder-open', 'square-check', 'check', 'bell', 'triangle-alert', 'repeat',
  'download', 'rotate-cw', 'chevron-left', 'chevron-right', 'video',
  'file-plus', 'upload-cloud', 'external-link',
  // note icon picker choices
  'sticky-note', 'book-open', 'briefcase', 'heart', 'star', 'lightbulb', 'flag', 'coffee',
  'music', 'code', 'graduation-cap', 'shopping-cart', 'plane', 'home', 'dumbbell', 'utensils',
  'wallet', 'calendar', 'map-pin', 'camera', 'gift', 'target', 'rocket', 'leaf', 'smile',
  'gamepad-2', 'clipboard-list', 'folder', 'sparkles', 'cake', 'paw-print', 'cloud',
  'menu', 'archive', 'archive-restore'
];

const srcDir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const outFile = path.join(__dirname, '..', 'renderer', 'icons.js');

// Keeps only the <svg>...</svg> element itself, dropping the license comment
// lucide-static puts in front of it. Slicing out the element (instead of
// regex-stripping comments, which a single pass can leave half-removed, e.g.
// "<!<!---->--") means no comment fragment can survive into the markup, and
// the check below fails the build if one is ever inside the element itself.
function extractSvg(raw, name) {
  const start = raw.indexOf('<svg');
  const end = raw.lastIndexOf('</svg>');
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${name}.svg: no <svg> element found`);
  }
  const svg = raw.slice(start, end + '</svg>'.length);
  if (svg.includes('<!--') || svg.includes('-->')) {
    throw new Error(`${name}.svg: unexpected comment inside <svg> element`);
  }
  return svg;
}

const entries = ICONS.map((name) => {
  const raw = fs.readFileSync(path.join(srcDir, `${name}.svg`), 'utf8');
  const svg = extractSvg(raw, name);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)}`;
});

const banner = '// Generated by scripts/sync-icons.js - do not edit by hand.\n' +
  '// Source: lucide-static (https://lucide.dev), bundled offline.\n';

fs.writeFileSync(
  outFile,
  `${banner}window.KEEPNOTES_ICONS = {\n${entries.join(',\n')}\n};\n`,
  'utf8'
);

console.log(`Wrote ${ICONS.length} icons to ${path.relative(process.cwd(), outFile)}`);
